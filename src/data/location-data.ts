export function stateNames() {
  return Object.keys(locationData).sort((a, b) => a.localeCompare(b));
}

export function districtsOf(state: string) {
  return Object.keys(locationData[state] ?? {});
}

export function talukasOf(state: string, district: string) {
  return locationData[state]?.[district] ?? [];
}

function norm(value: string) {
  return value.toLowerCase().replace(/[^a-z0-9]/g, "");
}

/** Map OpenWeather city/state names onto our India dropdowns. */
export function matchPlace(stateHint?: string | null, cityHint?: string | null) {
  const states = Object.keys(locationData);
  const stateN = stateHint ? norm(stateHint) : "";
  const cityN = cityHint ? norm(cityHint) : "";

  if (cityN) {
    for (const s of states) {
      for (const d of Object.keys(locationData[s] ?? {})) {
        const dn = norm(d);
        if (dn === cityN || dn.includes(cityN) || cityN.includes(dn)) {
          return { state: s, district: d, taluka: locationData[s][d][0] ?? "" };
        }
        for (const tk of locationData[s][d]) {
          const tn = norm(tk);
          if (tn === cityN || tn.includes(cityN) || cityN.includes(tn)) {
            return { state: s, district: d, taluka: tk };
          }
        }
      }
    }
  }

  const state =
    states.find((s) => norm(s) === stateN) ||
    states.find((s) => stateN && (norm(s).includes(stateN) || stateN.includes(norm(s)))) ||
    "Maharashtra";
  const districts = Object.keys(locationData[state] ?? {});
  const district = districts[0] ?? "Pune";
  return { state, district, taluka: locationData[state]?.[district]?.[0] ?? "" };
}


